"""Test every Gemini feature Sanjaya uses, against the real Gemini API, and print PASS/FAIL for each.

    export GEMINI_API_KEY=...
    python scripts/selftest.py

Nothing here is mocked. Speech for the voice tests is generated by Gemini's own text-to-speech, then sent
through the same transcription path the app uses for a phone's voice note.
"""
import asyncio
import io
import os
import sys
import time
import wave
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ.setdefault("SANJAYA_RUNTIME_DIR", str(Path(__file__).resolve().parent.parent / "runtime"))

from app.config import DATA_DIR, GEMINI_API_KEY  # noqa: E402

RESULTS = []


def report(name, ok, detail="", secs=None):
    RESULTS.append(ok)
    mark = "PASS" if ok else ("SKIP" if ok is None else "FAIL")
    t = f" ({secs:.1f}s)" if secs is not None else ""
    print(f"[{mark}] {name}{t}\n       {detail}"[:900], flush=True)


def run(name, fn):
    start = time.time()
    try:
        ok, detail = fn()
    except Exception as exc:
        ok, detail = False, f"{type(exc).__name__}: {str(exc)[:500]}"
    report(name, ok, detail, time.time() - start)


def pcm_to_wav(pcm, rate=24000):
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm)
    return buf.getvalue()


def main():
    if not GEMINI_API_KEY:
        print("GEMINI_API_KEY is not set. Run: export GEMINI_API_KEY=your_key")
        sys.exit(2)

    from google.genai import types
    from app.engine import Engine
    from app import onboarding

    engine = Engine()
    gem = engine.brain.gemini

    # 1. Model discovery
    def models():
        text, live = gem.discover()
        gem.check()
        if gem.status != "ok":
            return False, f"No model answered. {gem.error}"
        return True, (f"using {gem.model}; fallbacks {gem.candidates}; live model {gem.live_model}; "
                      f"key can use {len(text)} text models: {text[:6]}")
    run("Find a Gemini model this key can use", models)
    if gem.status != "ok":
        print("\nStopping: nothing else can work without a model.")
        sys.exit(1)

    plant = engine.plant

    # 2. Understanding a chat message (JSON schema output)
    def interpret_text():
        r = gem.interpret("Alarm baar baar baj raha tha, mute kar diya", plant.user("suresh"), plant)
        ok = r["kind"] == "routine_change" and "alarm_TAH-301" in r["tags"]
        return ok, f"kind={r['kind']} tags={r['tags']} summary={r['summary']!r}"
    run("Understand a Hinglish chat message", interpret_text)

    # 3. Reading a photo
    def interpret_photo():
        img = (DATA_DIR / "demo_media" / "alarm_panel_muted.png").read_bytes()
        r = gem.interpret("", plant.user("suresh"), plant, [{"bytes": img, "mime": "image/png"}])
        seen = (r.get("seen") or "") + " " + r.get("summary", "")
        ok = "alarm_TAH-301" in r["tags"] or ("TAH-301" in seen and ("mute" in seen.lower() or "bypass" in seen.lower()))
        return ok, f"kind={r['kind']} tags={r['tags']} seen={r.get('seen')!r}"
    run("Read a photo (muted alarm panel)", interpret_photo)

    # 4. Reading a datasheet PDF
    def datasheet():
        pdf = (DATA_DIR / "datasheets" / "brightline_bf105.pdf").read_bytes()
        s = gem.extract_specs({"bytes": pdf, "mime": "application/pdf"})
        ok = s.get("airflow_m3h") == 10500 and not s.get("ex_marking") and s.get("temperature_class") == "T3"
        return ok, str(s)
    run("Read a supplier datasheet (PDF)", datasheet)

    # 5. Decisions
    def decision():
        d = gem.parse_decision("Yes, but 15 minutes max", "Shut down Boiler B-1")
        return d["decision"] == "approve_with_conditions" and d["max_minutes"] == 15, str(d)
    run("Understand an approver's decision", decision)

    # 6. Agent with tools
    def ask():
        steps = []
        answer = gem.ask("Boiler B-1 kitni der band kar sakte hain?", plant.user("arjun"), engine.tool_call,
                         lambda n, a, r: steps.append(n))
        ok = bool(answer) and "20" in answer
        return ok, f"tools called: {steps}; answer: {answer!r}"
    run("Answer a question using plant tools (agent)", ask)

    # 7-8. Voice notes: Gemini speaks, then the app transcribes it
    tts = None
    try:
        for m in gem.client.models.list():
            name = (m.name or "").split("/")[-1]
            if "tts" in name and "generateContent" in (m.supported_actions or []):
                tts = name
                break
    except Exception:
        pass

    def voice(sentence, expect, user):
        def check():
            if not tts:
                return None, "No Gemini text-to-speech model available to this key, so no test audio."
            resp = gem.client.models.generate_content(
                model=tts, contents=f"Say clearly: {sentence}",
                config=types.GenerateContentConfig(
                    response_modalities=["AUDIO"],
                    speech_config=types.SpeechConfig(voice_config=types.VoiceConfig(
                        prebuilt_voice_config=types.PrebuiltVoiceConfig(voice_name="Kore")))))
            pcm = resp.candidates[0].content.parts[0].inline_data.data
            wav = pcm_to_wav(pcm)
            path = Path(os.environ["SANJAYA_RUNTIME_DIR"]) / f"selftest_{user}.wav"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(wav)
            text, mode = engine.brain.transcribe([{"kind": "voice", "path": path, "mime": "audio/wav"}])
            if mode != "gemini":
                return False, f"transcription failed: {engine.brain.last_error}"
            ok = any(e in (text or "").lower() for e in expect)
            return ok, f"tts={tts}; heard: {text!r}"
        return check
    run("Transcribe an English voice note", voice("Yes, but fifteen minutes maximum.", ["15", "fifteen"], "ravi"))
    run("Transcribe a Hindi voice note", voice("आज का बैच चार सौ से बढ़ाकर चार सौ अस्सी किलो कर दिया है।",
                                               ["480", "४८०", "चार सौ अस्सी", "बैच"], "arjun"))

    # 9. The whole app path: a voice note posted to the group chat becomes a logged change
    def app_flow():
        path = Path(os.environ["SANJAYA_RUNTIME_DIR"]) / "selftest_arjun.wav"
        if not path.exists():
            return None, "Skipped: no Hindi test audio (see previous test)."
        engine.reset()
        asyncio.run(engine.post("arjun", "", [{"kind": "voice", "path": path, "mime": "audio/wav",
                                               "name": "voice.wav", "url": "/x"}]))
        msg = next(m for m in engine.messages if m["author"] == "arjun")
        changes = [c["summary"] for c in engine.active_changes()]
        ok = any("batch_size" in c["tags"] for c in engine.active_changes())
        return ok, f"transcript={msg['transcript']!r}; changes logged={changes}"
    run("Voice note in the group chat becomes a logged change", app_flow)

    # 10. Live API (voice calls)
    def live():
        if not gem.live_model:
            return None, "No Live API model available to this key; live calls will be unavailable."

        async def go():
            got = 0
            cfg = types.LiveConnectConfig(response_modalities=["AUDIO"])
            async with gem.client.aio.live.connect(model=gem.live_model, config=cfg) as s:
                await s.send_client_content(turns=types.Content(role="user", parts=[types.Part(text="Say: hello Ravi.")]),
                                            turn_complete=True)
                async for r in s.receive():
                    if r.data:
                        got += len(r.data)
                    if r.server_content and r.server_content.turn_complete:
                        break
            return got
        got = asyncio.run(asyncio.wait_for(go(), 40))
        return got > 0, f"model {gem.live_model}; received {got} bytes of audio"
    run("Live voice call (Gemini Live API)", live)

    # 11. Teach Sanjaya: draft the risk model from documents
    def onboard():
        draft = onboarding.extract_with_gemini(gem, onboarding.sample_attachments(),
                                               {b["tag"] for h in plant.hazards for b in h["barriers"]})
        limits = [(l["equipment"], l["value"], l["unit"]) for l in draft["limits"]]
        ok = len(draft["hazards"]) >= 3 and any(v == 20 for _, v, _ in limits)
        return ok, f"{len(draft['hazards'])} hazards, limits={limits}, gaps={len(draft['gaps'])}"
    run("Draft the risk model from HAZOP/SOP PDFs", onboard)

    passed = sum(1 for r in RESULTS if r is True)
    failed = sum(1 for r in RESULTS if r is False)
    skipped = sum(1 for r in RESULTS if r is None)
    print(f"\n{passed} passed, {failed} failed, {skipped} skipped")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
